int	check_dupl(int board[][4])
{
	int	i;
	int	j;
	int	k;

	i = 0;
	while (i < 4)
	{
		j = 0;
		while (j < 4)
		{
			k = j + 1;
			while (k < 4)
			{
				if (board[j][i] == board[k][i])
					return (0);
				k++;
			}
			j++;
		}
		i++;
	}
	return (1);
}
