char	*ft_strupcase(char *str)
{
	char	*temp;

	temp = str;
	if (*str == 0)
		return (str);
	while (*str)
	{
		if ('a' <= *str && 'z' >= *str)
			*str -= 32;
		str++;
	}
	return (temp);
}
