char	*ft_strlowcase(char *str)
{
	char	*temp;

	temp = str;
	if (*str == 0)
		return (str);
	while (*str)
	{
		if ('A' <= *str && 'Z' >= *str)
			*str += 32;
		str++;
	}
	return (temp);
}
